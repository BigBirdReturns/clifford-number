#!/usr/bin/env bash
# Generates the deletion batches from branches.tsv. It only WRITES FILES in this directory;
# it never talks to GitHub and never deletes anything.
#
#   bash make-delete-plan.sh
#
# Output:
#   delete-order.tsv     tier<TAB>branch, in deletion order (tiers 1-5, then name, C locale)
#   batch-00.txt ...     100 branch names per file (tiers 1-4; the last file has the remainder)
#   batch-pr-heads.txt   the 3 branches that head open PRs (tier 5): delete only after the PRs are closed
#   delete-plan.sh       one `git push origin --delete ...` command per batch file, behind an exit-1 guard
#
# NOTE: written after the analysis session's worktree was removed, so this generator has not been executed
# by its author. Read delete-order.tsv and the first batch before trusting it.
set -euo pipefail
cd "$(dirname "$0")"
export LC_ALL=C
tab="$(printf '\t')"

# branches.tsv columns: 1 name 2 tip_sha 3 tip_date 4 ahead_of_main 5 reachable_from 6 has_pr 7 archived_in
#                       8 class 9 decision 10 reason 11 research_unique_files 12 archived_files 13 uncovered_files 14 flags
# tier 1 reachable from a keep ref / tag; 2 no unique research or only older versions; 3 carrier/controller/temp class;
# tier 4 research archived under archive/; 5 head of an open PR.
awk -F'\t' 'NR > 1 && $9 == "DELETE" {
  t = 2
  if ($14 ~ /OPEN-PR/) t = 5
  else if ($5 != "none") t = 1
  else if ($8 == "carrier/controller/temp") t = 3
  else if ($7 != "-") t = 4
  print t "\t" $1
}' branches.tsv | sort -t "$tab" -k1,1n -k2,2 > delete-order.tsv

rm -f batch-[0-9][0-9].txt batch-pr-heads.txt
awk -F'\t' '$1 < 5 { print $2 }' delete-order.tsv | split -d -a 2 -l 100 --additional-suffix=.txt - batch-
awk -F'\t' '$1 == 5 { print $2 }' delete-order.tsv > batch-pr-heads.txt

{
  echo '#!/usr/bin/env bash'
  echo '# GENERATED by make-delete-plan.sh. DO NOT RUN until the owner has approved and preflight.sh printed nothing.'
  echo 'echo "deletion plan, not approved: remove this line to run" >&2; exit 1'
  echo 'set -euo pipefail'
  for f in batch-[0-9][0-9].txt batch-pr-heads.txt; do
    n="$(wc -l < "$f")"
    echo
    echo "# $f ($n branches)"
    echo 'git push origin --delete \'
    sed '$!s/$/ \\/; s/^/  /' "$f"
  done
} > delete-plan.sh

echo "delete-order.tsv: $(wc -l < delete-order.tsv) branches; batches: $(ls batch-[0-9][0-9].txt | wc -l) x100 (last shorter) + batch-pr-heads.txt ($(wc -l < batch-pr-heads.txt))"
