assert.equal(byId.get('M04E-CA-018').classification.effective_power_id,'P4-compulsory-revision-reversal-or-termination');
assert.equal(byId.get('M04E-CA-019').classification.effective_power_id,'P1-voice-feedback-or-petition');
assert.equal(byId.get('M04E-CA-020').classification.constitutional_position_ids.includes('K4-counter-sovereign'),false);
assert.deepEqual(byId.get('M04E-CA-028').classification.class_ids,['C17-constitutionally-subordinate-resource-provider']);
assert.ok(byId.get('M04E-CA-031').classification.class_ids.includes('C04-aware-accommodator'));
assert.equal(byId.get('M04E-CA-032').classification.effective_power_id,'P3-gate-veto-or-collective-leverage');
assert.equal(byId.get('M04E-CA-033').classification.material_relation_ids.includes('M11-transition-or-exit-provider'),true);
assert.equal(report.source_fingerprint.length,64);
assert.equal(method.boundaries.position_proves_awareness,false);
assert.equal(estate.boundaries.represented_status_proves_unawareness_or_consent,false);
