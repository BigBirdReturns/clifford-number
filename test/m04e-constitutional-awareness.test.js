import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const method=read('data/project/m04e-constitutional-awareness-methodology.json');
const wave=read('data/intake/m04e-constitutional-awareness-estate-wave-01.json');
const estate=read('data/project/m04e-constitutional-awareness-estate.json');
const report=read('reports/core-thesis/constitutional-awareness/data.json');
const byId=new Map(wave.records.map(x=>[x.record_id,x]));
assert.equal(wave.records.length,33);
assert.equal(wave.subjects.length,31);
assert.equal(wave.source_registry.length,27);
assert.equal(estate.system_chains.length,6);
assert.equal(estate.counts.represented_records_with_direct_subject_voice,0);
assert.ok(estate.counts.by_position['O3-operator-integrator']>estate.counts.by_position['K4-counter-sovereign']);
assert.ok(estate.counts.by_power['P1-voice-feedback-or-petition']>estate.counts.by_power['P4-compulsory-revision-reversal-or-termination']);
assert.ok(estate.counts.unpopulated_or_not_directly_assignable_classes.includes('C03-tacit-constitutional-carrier'));
