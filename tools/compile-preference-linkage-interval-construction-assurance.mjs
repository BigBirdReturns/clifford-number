import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferenceLinkageIntervalConstructionAssuranceFixture, renderPreferenceLinkageIntervalConstructionAssuranceMarkdown } from './lib/preference-linkage-interval-construction-assurance.mjs';
const fixturePath = process.argv[2] ?? 'data/research/preference-custody/linkage-interval-construction-assurance.fixture.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-linkage-interval-construction-assurance.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-linkage-interval-construction-assurance.md';
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
const compiled = compilePreferenceLinkageIntervalConstructionAssuranceFixture(fixture);
mkdirSync(dirname(jsonPath), { recursive: true }); mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n'); writeFileSync(markdownPath, renderPreferenceLinkageIntervalConstructionAssuranceMarkdown(compiled));
console.log(`compiled ${compiled.fixture_id} -> ${jsonPath}, ${markdownPath}`);
