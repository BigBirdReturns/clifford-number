import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferencePreIntakeAssuranceFixture, renderPreferencePreIntakeAssuranceMarkdown } from './lib/preference-pre-intake-assurance.mjs';
const fixturePath = process.argv[2] ?? 'data/research/preference-custody/pre-intake-assurance.fixture.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-pre-intake-assurance.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-pre-intake-assurance.md';
const compiled = compilePreferencePreIntakeAssuranceFixture(JSON.parse(readFileSync(fixturePath, 'utf8')));
mkdirSync(dirname(jsonPath), { recursive: true });
mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n');
writeFileSync(markdownPath, renderPreferencePreIntakeAssuranceMarkdown(compiled));
console.log(`compiled ${compiled.fixture_id} -> ${jsonPath}, ${markdownPath}`);
