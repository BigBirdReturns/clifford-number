import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferenceCustodyManifestV38, renderPreferenceCustodyManifestV38Markdown } from './lib/preference-custody-manifest-v38.mjs';
execFileSync(process.execPath, ['tools/compile-preference-custody-manifest-v37.mjs'], { stdio: 'inherit' });
execFileSync(process.execPath, ['tools/compile-preference-linkage-confidence-adjudication-assurance.mjs'], { stdio: 'inherit' });
const manifestPath = process.argv[2] ?? 'data/research/preference-custody/control-manifest-v38.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-custody-laboratory-floor-v38.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-custody-laboratory-floor-v38.md';
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const baseBuild = JSON.parse(readFileSync('build/research/preference-custody-laboratory-floor-v37.json', 'utf8'));
const confidenceBuild = JSON.parse(readFileSync('build/research/preference-linkage-confidence-adjudication-assurance.json', 'utf8'));
const confidenceFixture = JSON.parse(readFileSync(manifest.extension_control.source_fixture_path, 'utf8'));
const compiled = compilePreferenceCustodyManifestV38(manifest, baseBuild, confidenceBuild, confidenceFixture);
mkdirSync(dirname(jsonPath), { recursive: true });
mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n');
writeFileSync(markdownPath, renderPreferenceCustodyManifestV38Markdown(compiled));
console.log(`compiled ${compiled.manifest_id} -> ${jsonPath}, ${markdownPath}`);
