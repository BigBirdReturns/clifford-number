import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferenceEligibilityOutreachAssuranceFixture, renderPreferenceEligibilityOutreachAssuranceMarkdown } from './lib/preference-eligibility-outreach-assurance.mjs';
const fixturePath = process.argv[2] ?? 'data/research/preference-custody/eligibility-outreach-assurance.fixture.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-eligibility-outreach-assurance.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-eligibility-outreach-assurance.md';
const compiled = compilePreferenceEligibilityOutreachAssuranceFixture(JSON.parse(readFileSync(fixturePath, 'utf8')));
mkdirSync(dirname(jsonPath), { recursive: true });
mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n');
writeFileSync(markdownPath, renderPreferenceEligibilityOutreachAssuranceMarkdown(compiled));
console.log(`compiled ${compiled.fixture_id} -> ${jsonPath}, ${markdownPath}`);
