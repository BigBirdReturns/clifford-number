import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferenceLinkageUncertaintyMonitoringAssuranceFixture, renderPreferenceLinkageUncertaintyMonitoringAssuranceMarkdown } from './lib/preference-linkage-uncertainty-monitoring-assurance.mjs';
const fixturePath = process.argv[2] ?? 'data/research/preference-custody/linkage-uncertainty-monitoring-assurance.fixture.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-linkage-uncertainty-monitoring-assurance.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-linkage-uncertainty-monitoring-assurance.md';
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
const compiled = compilePreferenceLinkageUncertaintyMonitoringAssuranceFixture(fixture);
mkdirSync(dirname(jsonPath), { recursive: true });
mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n');
writeFileSync(markdownPath, renderPreferenceLinkageUncertaintyMonitoringAssuranceMarkdown(compiled));
console.log(`compiled ${compiled.fixture_id} -> ${jsonPath}, ${markdownPath}`);
