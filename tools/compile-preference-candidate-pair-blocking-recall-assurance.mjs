import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { compilePreferenceCandidatePairBlockingRecallAssuranceFixture, renderPreferenceCandidatePairBlockingRecallAssuranceMarkdown } from './lib/preference-candidate-pair-blocking-recall-assurance.mjs';
const fixturePath = process.argv[2] ?? 'data/research/preference-custody/candidate-pair-blocking-recall-assurance.fixture.json';
const jsonPath = process.argv[3] ?? 'build/research/preference-candidate-pair-blocking-recall-assurance.json';
const markdownPath = process.argv[4] ?? 'build/research/preference-candidate-pair-blocking-recall-assurance.md';
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
const compiled = compilePreferenceCandidatePairBlockingRecallAssuranceFixture(fixture);
mkdirSync(dirname(jsonPath), { recursive: true });
mkdirSync(dirname(markdownPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(compiled, null, 2) + '\n');
writeFileSync(markdownPath, renderPreferenceCandidatePairBlockingRecallAssuranceMarkdown(compiled));
console.log(`compiled ${compiled.fixture_id} -> ${jsonPath}, ${markdownPath}`);
